import jsPDFLib from 'jspdf'
import { applyPlugin } from 'jspdf-autotable'
const jsPDF = jsPDFLib.jsPDF || jsPDFLib.default || jsPDFLib
applyPlugin(jsPDF)
import { formatCurrency } from './helpers'
import { ALL_CATEGORIES } from './constants'

const PW = 210
const PH = 297
const M = 20
const CW = PW - 2 * M
const COL_NEON = [0, 255, 136]
const COL_WHITE = [255, 255, 255]
const COL_MUTED = [160, 160, 180]
const COL_INCOME = [74, 222, 128]
const COL_EXPENSE = [239, 68, 68]
const COL_SAVINGS = [0, 200, 255]
const COL_CARD = [25, 25, 42]
const COL_BG = [15, 15, 26]
const COL_BORDER = [35, 35, 55]

const CATEGORY_COLORS = [
  [255, 107, 107], [255, 159, 67], [255, 205, 86],
  [80, 200, 120], [72, 187, 255], [156, 136, 255],
  [255, 99, 132], [84, 194, 184], [200, 150, 100],
  [150, 200, 150], [200, 180, 100], [100, 150, 200],
]

function getCatColor(i) {
  return CATEGORY_COLORS[i % CATEGORY_COLORS.length]
}

function getCatLabel(id) {
  const c = ALL_CATEGORIES.find((x) => x.id === id)
  return c ? c.label : id
}

function fmt(n) {
  return formatCurrency(n)
}

function getMonthName(m) {
  const names = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
  return names[m] || ''
}

function getFullMonth(m) {
  const names = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
  return names[m] || ''
}

function addFooter(doc, pageNum, totalPages) {
  const y = PH - 12
  doc.setFontSize(7)
  doc.setTextColor(...COL_MUTED)
  doc.text('Generated by FINORA', M, y)
  doc.text(`Page ${pageNum} of ${totalPages}`, PW - M, y, { align: 'right' })
  doc.setDrawColor(...COL_BORDER)
  doc.line(M, y - 2, PW - M, y - 2)
}

function addPageNumber(doc, pageNum, totalPages) {
  const y = PH - 12
  doc.setFontSize(7)
  doc.setTextColor(...COL_MUTED)
  doc.text('Generated by FINORA', M, y)
  doc.text(`Page ${pageNum} of ${totalPages}`, PW - M, y, { align: 'right' })
}

function drawCover(doc, title, periodLabel) {
  doc.setFillColor(...COL_CARD)
  doc.rect(0, 0, PW, PH, 'F')
  doc.setFillColor(...COL_BG)
  doc.rect(M, M, CW, PH - 2 * M, 'F')
  const cx = PW / 2
  doc.setFontSize(36)
  doc.setTextColor(...COL_NEON)
  doc.text('FINORA', cx, 90, { align: 'center' })
  doc.setFontSize(16)
  doc.setTextColor(100, 255, 180)
  doc.text('FINANCE', cx, 108, { align: 'center' })
  doc.setDrawColor(...COL_NEON)
  doc.setLineWidth(0.5)
  doc.line(cx - 20, 118, cx + 20, 118)
  doc.setFontSize(20)
  doc.setTextColor(...COL_WHITE)
  doc.text('Financial Report', cx, 142, { align: 'center' })
  doc.setFontSize(11)
  doc.setTextColor(...COL_MUTED)
  doc.text(title, cx, 162, { align: 'center' })
  doc.text(periodLabel, cx, 178, { align: 'center' })
  const d = new Date()
  const dateStr = `${d.getDate()} ${getFullMonth(d.getMonth())} ${d.getFullYear()}`
  doc.setFontSize(9)
  doc.text(`Generated: ${dateStr}`, cx, 198, { align: 'center' })
  doc.setFontSize(8)
  doc.setTextColor(...COL_MUTED)
  doc.text('This report provides a comprehensive overview of your financial activities', cx, 230, { align: 'center' })
  doc.text('for the selected period. All figures are in Indian Rupees (INR).', cx, 242, { align: 'center' })
  doc.setFontSize(8)
  doc.setTextColor(80, 80, 100)
  doc.text('FINORA \u2022 Confidential', cx, 270, { align: 'center' })
}

function drawSummaryCards(doc, data) {
  const cards = [
    { label: 'Total Income', value: fmt(data.totalIncome), color: COL_INCOME },
    { label: 'Total Expenses', value: fmt(data.totalExpense), color: COL_EXPENSE },
    { label: 'Net Savings', value: fmt(data.savings), color: data.savings >= 0 ? COL_SAVINGS : COL_EXPENSE },
    { label: 'Savings Rate', value: data.savingsRate != null ? `${data.savingsRate.toFixed(1)}%` : 'N/A', color: COL_NEON },
  ]
  const cardW = (CW - 6) / 2
  const cardH = 32
  const startY = 35
  cards.forEach((card, i) => {
    const col = i % 2
    const row = Math.floor(i / 2)
    const x = M + col * (cardW + 6)
    const y = startY + row * (cardH + 6)
    doc.setFillColor(...COL_CARD)
    doc.roundedRect(x, y, cardW, cardH, 2, 2, 'F')
    doc.setFontSize(7)
    doc.setTextColor(...COL_MUTED)
    doc.text(card.label, x + 8, y + 12)
    doc.setFontSize(14)
    doc.setTextColor(...card.color)
    doc.text(card.value, x + 8, y + 26)
  })
}

function drawCategoryChart(doc, breakdown, startY) {
  doc.setFontSize(12)
  doc.setTextColor(...COL_WHITE)
  doc.text('Expense by Category', M, startY)
  const chartTop = startY + 8
  const barH = 12
  const gap = 4
  const labelW = 40
  const valW = 45
  const barMaxW = CW - labelW - valW - 4
  const total = breakdown.reduce((s, c) => s + c.amount, 0) || 1
  const maxAmt = Math.max(...breakdown.map((c) => c.amount), 1)
  const showCount = Math.min(breakdown.length, 8)
  breakdown.sort((a, b) => b.amount - a.amount)
  const top = breakdown.slice(0, showCount)
  const remaining = breakdown.slice(showCount)
  if (remaining.length > 0) {
    top.push({ category: 'other', amount: remaining.reduce((s, c) => s + c.amount, 0) })
  }
  doc.setFontSize(7)
  top.forEach((item, i) => {
    const y = chartTop + i * (barH + gap)
    const pct = (item.amount / total) * 100
    const bw = (item.amount / maxAmt) * barMaxW
    doc.setTextColor(...COL_MUTED)
    doc.text(getCatLabel(item.category), M, y + 8)
    doc.setFillColor(...getCatColor(i))
    doc.roundedRect(M + labelW + 2, y + 1, Math.max(bw, 2), barH - 2, 1, 1, 'F')
    doc.setTextColor(...COL_WHITE)
    doc.text(`${fmt(item.amount)}  (${pct.toFixed(1)}%)`, M + labelW + 4 + Math.max(bw, 4), y + 8, { maxWidth: valW })
  })
  const h = top.length * (barH + gap)
  return chartTop + h + 10
}

function drawTrendChart(doc, monthlyData, startY) {
  doc.setFontSize(12)
  doc.setTextColor(...COL_WHITE)
  doc.text('Income vs Expense Trend', M, startY)
  const chartTop = startY + 10
  const chartH = 55
  const chartW = CW
  const chartLeft = M
  const chartBottom = chartTop + chartH
  const count = monthlyData.length
  if (count === 0) return chartBottom + 10
  const allVals = monthlyData.flatMap((m) => [m.income || 0, m.expense || 0])
  const maxVal = Math.max(...allVals, 1) * 1.15
  const barW = Math.min((chartW - (count - 1) * 4) / (count * 2 + 1), 12)
  const groupW = barW * 2 + 4
  const totalGroupW = count * groupW
  const offsetX = chartLeft + (chartW - totalGroupW) / 2
  doc.setDrawColor(...COL_BORDER)
  doc.line(chartLeft, chartBottom, chartLeft + chartW, chartBottom)
  monthlyData.forEach((m, i) => {
    const gx = offsetX + i * groupW
    const ih = ((m.income || 0) / maxVal) * chartH
    const eh = ((m.expense || 0) / maxVal) * chartH
    doc.setFillColor(...COL_INCOME)
    doc.rect(gx, chartBottom - ih, barW, ih, 'F')
    doc.setFillColor(...COL_EXPENSE)
    doc.rect(gx + barW + 4, chartBottom - eh, barW, eh, 'F')
    doc.setFontSize(6)
    doc.setTextColor(...COL_MUTED)
    doc.text(getMonthName(m.month), gx + barW / 2 - 5, chartBottom + 5)
  })
  doc.setFontSize(6)
  doc.setTextColor(...COL_INCOME)
  doc.text('\u25A0 Income', PW - M - 40, chartTop - 2)
  doc.setTextColor(...COL_EXPENSE)
  doc.text('\u25A0 Expense', PW - M - 12, chartTop - 2)
  for (let v = 0; v <= maxVal; v += maxVal / 4) {
    const yPos = chartBottom - (v / maxVal) * chartH
    if (yPos >= chartTop) {
      doc.setFontSize(5)
      doc.setTextColor(...COL_MUTED)
      doc.text(fmt(Math.round(v)), chartLeft - 2, yPos + 1, { align: 'right' })
    }
  }
  return chartBottom + 12
}

function drawSavingsChart(doc, monthlyData, startY) {
  doc.setFontSize(12)
  doc.setTextColor(...COL_WHITE)
  doc.text('Monthly Savings Trend', M, startY)
  const chartTop = startY + 10
  const chartH = 50
  const chartW = CW
  const chartLeft = M
  const chartBottom = chartTop + chartH
  const count = monthlyData.length
  if (count === 0) return chartBottom + 10
  const savings = monthlyData.map((m) => (m.income || 0) - (m.expense || 0))
  const absMax = Math.max(...savings.map(Math.abs), 1) * 1.2
  const zeroY = chartTop + chartH / 2
  const range = absMax * 2
  const barW = Math.min((chartW - (count - 1) * 6) / count, 16)
  const totalBarW = count * barW + (count - 1) * 6
  const offsetX = chartLeft + (chartW - totalBarW) / 2
  doc.setDrawColor(...COL_BORDER)
  doc.line(chartLeft, zeroY, chartLeft + chartW, zeroY)
  savings.forEach((s, i) => {
    const bx = offsetX + i * (barW + 6)
    const bh = Math.abs(s / range) * chartH
    const by = s >= 0 ? zeroY - bh : zeroY
    doc.setFillColor(...(s >= 0 ? COL_SAVINGS : COL_EXPENSE))
    doc.rect(bx, by, barW, Math.max(bh, 1), 'F')
    doc.setFontSize(6)
    doc.setTextColor(...COL_MUTED)
    doc.text(getMonthName(monthlyData[i].month), bx + barW / 2 - 5, zeroY + 8)
  })
  return chartBottom + 12
}

function drawTxnSummary(doc, data) {
  doc.setFontSize(12)
  doc.setTextColor(...COL_WHITE)
  doc.text('Transaction Summary', M, 35)
  const items = [
    { label: 'Total Transactions', value: String(data.totalTxns) },
    { label: 'Largest Expense', value: fmt(data.largestExpense) },
    { label: 'Largest Income', value: fmt(data.largestIncome) },
    { label: 'Most Used Category', value: data.mostUsedCategory },
  ]
  items.forEach((item, i) => {
    const row = Math.floor(i / 2)
    const col = i % 2
    const x = M + col * (CW / 2)
    const y = 50 + row * 14
    doc.setFontSize(8)
    doc.setTextColor(...COL_MUTED)
    doc.text(item.label, x, y)
    doc.setFontSize(11)
    doc.setTextColor(...COL_WHITE)
    doc.text(item.value, x, y + 10)
  })
  const recentY = 90
  if (data.recentTransactions.length > 0) {
    doc.setFontSize(10)
    doc.setTextColor(...COL_WHITE)
    doc.text('Recent Transactions', M, recentY)
    const rows = data.recentTransactions.slice(0, 15).map((t) => [
      t.date || '',
      getCatLabel(t.category) || '',
      t.person?.name || '',
      t.type === 'income' ? fmt(t.amount) : '',
      t.type === 'expense' ? fmt(t.amount) : '',
    ])
    doc.autoTable({
      startY: recentY + 4,
      head: [['Date', 'Category', 'Person', 'Income', 'Expense']],
      body: rows,
      theme: 'grid',
      headStyles: { fillColor: COL_NEON, textColor: [0, 0, 0], fontSize: 7, fontStyle: 'bold' },
      bodyStyles: { fillColor: COL_CARD, textColor: COL_WHITE, fontSize: 6, lineColor: COL_BORDER },
      alternateRowStyles: { fillColor: COL_BG },
      margin: { left: M, right: M },
      styles: { cellPadding: 2 },
      tableWidth: CW,
    })
  }
}

function buildReport(type, transactions, config) {
  let title = ''
  let periodLabel = ''
  let filtered = [...transactions]
  let computeSummaryCards = () => ({ totalIncome: 0, totalExpense: 0, savings: 0, savingsRate: 0 })
  let computeCategoryBreakdown = () => []
  let computeMonthlyData = () => []
  let computeTxnSummary = () => ({ totalTxns: 0, largestExpense: 0, largestIncome: 0, mostUsedCategory: 'N/A', recentTransactions: [] })
  if (type === 'monthly') {
    const { month, year } = config
    title = `Monthly Report \u2014 ${getFullMonth(month)} ${year}`
    const range = getMonthDateRange(month, year)
    periodLabel = `Period: ${range.start} \u2014 ${range.end}`
    filtered = transactions.filter((t) => t.date >= range.start && t.date <= range.end)
  } else if (type === 'category') {
    const { month, year } = config
    title = `Category Report \u2014 ${getFullMonth(month)} ${year}`
    const range = getMonthDateRange(month, year)
    periodLabel = `Period: ${range.start} \u2014 ${range.end}`
    filtered = transactions.filter((t) => t.date >= range.start && t.date <= range.end)
  } else if (type === 'daterange') {
    const { dateFrom, dateTo } = config
    title = `Date Range Report`
    periodLabel = `Period: ${dateFrom} \u2014 ${dateTo}`
    filtered = transactions.filter((t) => t.date >= dateFrom && t.date <= dateTo)
  } else if (type === 'annual') {
    const { year } = config
    title = `Annual Summary \u2014 ${year}`
    periodLabel = `Year: ${year}`
    const start = `${year}-01-01`
    const end = `${year}-12-31`
    filtered = transactions.filter((t) => t.date >= start && t.date <= end)
  }
  const totalIncome = filtered.filter((t) => t.type === 'income').reduce((s, t) => s + t.amount, 0)
  const totalExpense = filtered.filter((t) => t.type === 'expense').reduce((s, t) => s + t.amount, 0)
  const savings = totalIncome - totalExpense
  const savingsRate = totalIncome > 0 ? (savings / totalIncome) * 100 : 0
  const expBreakdown = groupBy(filtered.filter((t) => t.type === 'expense'), 'category')
    .map(([cat, txs]) => ({ category: cat, amount: txs.reduce((s, t) => s + t.amount, 0) }))
  const incItems = filtered.filter((t) => t.type === 'income')
  const expItems = filtered.filter((t) => t.type === 'expense')
  const largestExpense = expItems.length > 0 ? Math.max(...expItems.map((t) => t.amount)) : 0
  const largestIncome = incItems.length > 0 ? Math.max(...incItems.map((t) => t.amount)) : 0
  const catCounts = {}
  filtered.forEach((t) => { catCounts[t.category] = (catCounts[t.category] || 0) + 1 })
  let mostUsedCategory = 'N/A'
  let maxCount = 0
  Object.entries(catCounts).forEach(([cat, cnt]) => {
    if (cnt > maxCount) { maxCount = cnt; mostUsedCategory = getCatLabel(cat) }
  })
  const recent = [...filtered].sort((a, b) => b.date.localeCompare(a.date)).slice(0, 15)
  let monthlyData = []
  if (type === 'annual') {
    for (let m = 0; m < 12; m++) {
      const range = getMonthDateRange(m, config.year)
      const mTxns = transactions.filter((t) => t.date >= range.start && t.date <= range.end)
      monthlyData.push({
        month: m,
        income: mTxns.filter((t) => t.type === 'income').reduce((s, t) => s + t.amount, 0),
        expense: mTxns.filter((t) => t.type === 'expense').reduce((s, t) => s + t.amount, 0),
      })
    }
  } else {
    const allMonthData = {}
    filtered.forEach((t) => {
      const m = parseInt(t.date.split('-')[1], 10) - 1
      if (!allMonthData[m]) allMonthData[m] = { month: m, income: 0, expense: 0 }
      if (t.type === 'income') allMonthData[m].income += t.amount
      else allMonthData[m].expense += t.amount
    })
    monthlyData = Object.values(allMonthData).sort((a, b) => a.month - b.month)
  }
  return { title, periodLabel, filtered, totalIncome, totalExpense, savings, savingsRate, expBreakdown, monthlyData, largestExpense, largestIncome, mostUsedCategory, totalTxns: filtered.length, recentTransactions: recent }
}

function getMonthDateRange(month, year) {
  const start = `${year}-${String(month + 1).padStart(2, '0')}-01`
  const lastDay = new Date(year, month + 1, 0).getDate()
  const end = `${year}-${String(month + 1).padStart(2, '0')}-${String(lastDay).padStart(2, '0')}`
  return { start, end }
}

function groupBy(items, key) {
  const map = new Map()
  items.forEach((item) => {
    const k = item[key]
    if (!map.has(k)) map.set(k, [])
    map.get(k).push(item)
  })
  return Array.from(map)
}

export function generateMonthlyReport(transactions, monthIndex, year) {
  const data = buildReport('monthly', transactions, { month: monthIndex, year })
  return generatePDF('monthly', data)
}

export function generateCategoryReport(transactions, monthIndex, year) {
  const data = buildReport('category', transactions, { month: monthIndex, year })
  return generatePDF('category', data)
}

export function generateDateRangeReport(transactions, dateFrom, dateTo) {
  const data = buildReport('daterange', transactions, { dateFrom, dateTo })
  return generatePDF('daterange', data)
}

export function generateAnnualReport(transactions, year) {
  const data = buildReport('annual', transactions, { year })
  return generatePDF('annual', data)
}

function generatePDF(type, data) {
  const doc = new jsPDF('p', 'mm', 'a4')
  doc.setFont('helvetica')
  drawCover(doc, data.title, data.periodLabel)
  doc.addPage()
  doc.setFillColor(...COL_BG)
  doc.rect(0, 0, PW, PH, 'F')
  drawSummaryCards(doc, data)
  let y = 82
  if (data.expBreakdown.length > 0) {
    y = drawCategoryChart(doc, data.expBreakdown, y)
  } else {
    doc.setFontSize(9)
    doc.setTextColor(...COL_MUTED)
    doc.text('No expense data available for this period.', M, y + 10)
    y += 20
  }
  if (data.monthlyData.length > 0) {
    y = drawTrendChart(doc, data.monthlyData, y + 8)
    if (type === 'annual' || data.monthlyData.length > 1) {
      y = drawSavingsChart(doc, data.monthlyData, y + 8)
    }
  } else {
    y += 5
  }
  if (y > PH - 50) { doc.addPage(); y = 20 }
  drawTxnSummary(doc, { ...data, recentTransactions: data.recentTransactions })
  const totalPages = doc.internal.getNumberOfPages()
  for (let i = 2; i <= totalPages; i++) {
    doc.setPage(i)
    doc.setFillColor(...COL_BG)
    doc.rect(0, 0, PW, PH, 'F')
    addPageNumber(doc, i, totalPages)
  }
  let blob
  try { blob = doc.output('blob') } catch { blob = null }
  const dataUri = doc.output('datauristring')
  return { blob, dataUri, doc, pageCount: totalPages }
}
