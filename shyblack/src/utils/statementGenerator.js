import jsPDFLib from 'jspdf'
import { applyPlugin } from 'jspdf-autotable'
const jsPDF = jsPDFLib.jsPDF || jsPDFLib.default || jsPDFLib
applyPlugin(jsPDF)
import { formatCurrency, formatDate } from './helpers'
import { getFrequencyLabel } from './emi'
import { ALL_CATEGORIES } from './constants'

const PW = 210
const PH = 297
const M = 20
const CW = PW - 2 * M
const COL_NEON = [0, 255, 136]
const COL_WHITE = [255, 255, 255]
const COL_MUTED = [160, 160, 180]
const COL_INCOME = [74, 222, 128]
const COL_EXPENSE = [239, 68, 68]
const COL_CARD = [25, 25, 42]
const COL_BG = [15, 15, 26]
const COL_BORDER = [35, 35, 55]
const COL_HEADING = [200, 200, 220]

function fmt(n) {
  return formatCurrency(n)
}

function addFooter(doc, pageNum, totalPages) {
  const y = PH - 12
  doc.setFontSize(7)
  doc.setTextColor(...COL_MUTED)
  doc.text('Generated by ShyBlack Finance', M, y)
  doc.text(`Page ${pageNum} of ${totalPages}`, PW - M, y, { align: 'right' })
  doc.setDrawColor(...COL_BORDER)
  doc.line(M, y - 2, PW - M, y - 2)
}

function addNewPage(doc, pageNum, totalPages) {
  doc.addPage()
  doc.setFillColor(...COL_BG)
  doc.rect(0, 0, PW, PH, 'F')
  addFooter(doc, pageNum, totalPages)
}

function drawSectionHeader(doc, title, y) {
  doc.setFontSize(13)
  doc.setTextColor(...COL_HEADING)
  doc.text(title, M, y)
  doc.setDrawColor(...COL_NEON)
  doc.setLineWidth(0.3)
  doc.line(M, y + 2, M + CW, y + 2)
  return y + 10
}

function drawSummaryCard(doc, label, value, color, x, y, w, h) {
  doc.setFillColor(...COL_CARD)
  doc.roundedRect(x, y, w, h, 2, 2, 'F')
  doc.setFontSize(7)
  doc.setTextColor(...COL_MUTED)
  doc.text(label, x + 6, y + 10)
  doc.setFontSize(12)
  doc.setTextColor(...color)
  doc.text(value, x + 6, y + 24)
}

export function generateEmiStatement(emi, paymentHistory) {
  const doc = new jsPDF('p', 'mm', 'a4')
  doc.setFont('helvetica')
  let pageNum = 1

  doc.setFillColor(...COL_CARD)
  doc.rect(0, 0, PW, PH, 'F')
  doc.setFillColor(...COL_BG)
  doc.rect(M, M, CW, PH - 2 * M, 'F')
  const cx = PW / 2
  doc.setFontSize(30)
  doc.setTextColor(...COL_NEON)
  doc.text('ShyBlack', cx, 80, { align: 'center' })
  doc.setFontSize(14)
  doc.setTextColor(100, 255, 180)
  doc.text('FINANCE', cx, 96, { align: 'center' })
  doc.setDrawColor(...COL_NEON)
  doc.setLineWidth(0.5)
  doc.line(cx - 15, 104, cx + 15, 104)
  doc.setFontSize(18)
  doc.setTextColor(...COL_WHITE)
  doc.text('EMI Statement', cx, 126, { align: 'center' })
  doc.setFontSize(11)
  doc.setTextColor(...COL_MUTED)
  doc.text(emi.name || 'EMI', cx, 144, { align: 'center' })
  doc.text(`Generated: ${new Date().toLocaleDateString()}`, cx, 162, { align: 'center' })
  doc.setFontSize(8)
  doc.setTextColor(...COL_MUTED)
  doc.text('ShyBlack Finance \u2022 Confidential', cx, 250, { align: 'center' })

  pageNum++
  addNewPage(doc, pageNum, 0)

  let y = 25
  y = drawSectionHeader(doc, 'EMI Details', y)
  const freqLabel = getFrequencyLabel(emi.frequency)
  const totalPaid = (emi.paymentHistory || []).reduce((s, p) => s + p.amount, 0)
  const totalPayable = emi.amount * (emi.tenure || 0)
  const details = [
    ['Loan Name', emi.name || '-'],
    ['Lender', emi.lender || '-'],
    ['Frequency', freqLabel],
    ['EMI Amount', fmt(emi.amount)],
    ['Total Tenure', `${emi.tenure || 0} ${freqLabel.toLowerCase()}`],
    ['Paid Count', `${emi.totalPaidCount || 0} of ${emi.tenure || 0}`],
    ['Total Paid', fmt(totalPaid)],
    ['Total Payable', fmt(totalPayable)],
    ['Remaining', fmt(Math.max(0, totalPayable - totalPaid))],
    ['Status', emi.status === 'closed' ? 'Closed' : emi.status === 'paused' ? 'Paused' : 'Active'],
    ['Start Date', emi.startDate ? formatDate(emi.startDate) : '-'],
    ['Last Paid', emi.lastPaidDate ? formatDate(emi.lastPaidDate) : '-'],
    ['Contact', emi.contactName || '-'],
  ]
  details.forEach(([label, value], i) => {
    const ry = y + i * 7
    if (ry > PH - 30) {
      pageNum++
      addNewPage(doc, pageNum, pageNum)
      y = 25
    }
    doc.setFontSize(8)
    doc.setTextColor(...COL_MUTED)
    doc.text(label, M, ry)
    doc.setFontSize(8)
    doc.setTextColor(...COL_WHITE)
    doc.text(value, M + 60, ry)
  })

  y = y + details.length * 7 + 10
  if (y > PH - 50) {
    pageNum++
    addNewPage(doc, pageNum, pageNum)
    y = 25
  }

  y = drawSectionHeader(doc, 'Payment History', y)
  const payments = (paymentHistory || []).slice().sort((a, b) => b.paidAt - a.paidAt)
  if (payments.length === 0) {
    doc.setFontSize(9)
    doc.setTextColor(...COL_MUTED)
    doc.text('No payments recorded yet.', M, y + 10)
  } else {
    const rows = payments.map((p) => [
      p.date || formatDate(new Date(p.paidAt)),
      fmt(p.amount),
      p.transactionId ? 'Auto' : 'Manual',
    ])
    doc.autoTable({
      startY: y + 4,
      head: [['Date', 'Amount', 'Type']],
      body: rows,
      theme: 'grid',
      headStyles: { fillColor: COL_NEON, textColor: [0, 0, 0], fontSize: 7, fontStyle: 'bold' },
      bodyStyles: { fillColor: COL_CARD, textColor: COL_WHITE, fontSize: 6, lineColor: COL_BORDER },
      alternateRowStyles: { fillColor: COL_BG },
      margin: { left: M, right: M },
      styles: { cellPadding: 2 },
      tableWidth: CW,
    })
  }

  const totalPages = doc.internal.getNumberOfPages()
  for (let i = 2; i <= totalPages; i++) {
    doc.setPage(i)
    addFooter(doc, i, totalPages)
  }
  const blob = doc.output('blob')
  const dataUri = doc.output('datauristring')
  return { blob, dataUri, doc, pageCount: totalPages }
}

export function generateLedgerStatement(ledger, payments) {
  const doc = new jsPDF('p', 'mm', 'a4')
  doc.setFont('helvetica')
  let pageNum = 1

  doc.setFillColor(...COL_CARD)
  doc.rect(0, 0, PW, PH, 'F')
  doc.setFillColor(...COL_BG)
  doc.rect(M, M, CW, PH - 2 * M, 'F')
  const cx = PW / 2
  doc.setFontSize(30)
  doc.setTextColor(...COL_NEON)
  doc.text('ShyBlack', cx, 80, { align: 'center' })
  doc.setFontSize(14)
  doc.setTextColor(100, 255, 180)
  doc.text('FINANCE', cx, 96, { align: 'center' })
  doc.setDrawColor(...COL_NEON)
  doc.setLineWidth(0.5)
  doc.line(cx - 15, 104, cx + 15, 104)
  doc.setFontSize(18)
  doc.setTextColor(...COL_WHITE)
  doc.text('Borrow / Lend Statement', cx, 126, { align: 'center' })
  doc.setFontSize(11)
  doc.setTextColor(...COL_MUTED)
  doc.text(ledger.personName || 'Person', cx, 144, { align: 'center' })
  doc.text(`Generated: ${new Date().toLocaleDateString()}`, cx, 162, { align: 'center' })
  doc.setFontSize(8)
  doc.setTextColor(...COL_MUTED)
  doc.text('ShyBlack Finance \u2022 Confidential', cx, 250, { align: 'center' })

  pageNum++
  addNewPage(doc, pageNum, 0)

  let y = 25
  y = drawSectionHeader(doc, 'Ledger Details', y)
  const totalRepaid = (payments || []).reduce((s, p) => s + p.amount, 0)
  const balance = (ledger.currentBalance ?? ledger.originalAmount ?? 0)
  const details = [
    ['Person', ledger.personName || '-'],
    ['Type', ledger.type === 'lent' ? 'Lent' : 'Borrowed'],
    ['Original Amount', fmt(ledger.originalAmount || 0)],
    ['Total Repaid', fmt(totalRepaid)],
    ['Balance', fmt(balance)],
    ['Status', ledger.status === 'settled' ? 'Settled' : 'Active'],
    ['Created', ledger.createdDate ? formatDate(new Date(ledger.createdDate)) : '-'],
    ['Settled', ledger.settlementDate ? formatDate(new Date(ledger.settlementDate)) : '-'],
  ]
  details.forEach(([label, value], i) => {
    const ry = y + i * 7
    doc.setFontSize(8)
    doc.setTextColor(...COL_MUTED)
    doc.text(label, M, ry)
    doc.setFontSize(8)
    doc.setTextColor(...COL_WHITE)
    doc.text(value, M + 60, ry)
  })

  y = y + details.length * 7 + 10
  if (y > PH - 50) {
    pageNum++
    addNewPage(doc, pageNum, pageNum)
    y = 25
  }

  y = drawSectionHeader(doc, 'Payment History', y)
  const sortedPayments = (payments || []).slice().sort((a, b) => (b.createdAt || b.paidAt || 0) - (a.createdAt || a.paidAt || 0))
  if (sortedPayments.length === 0) {
    doc.setFontSize(9)
    doc.setTextColor(...COL_MUTED)
    doc.text('No payments recorded yet.', M, y + 10)
  } else {
    let runningBalance = ledger.originalAmount || 0
    const rows = sortedPayments.map((p) => {
      runningBalance -= p.amount
      return [
        formatDate(new Date(p.createdAt || p.paidAt || Date.now())),
        fmt(p.amount),
        p.notes || '-',
        fmt(runningBalance),
      ]
    })
    doc.autoTable({
      startY: y + 4,
      head: [['Date', 'Amount', 'Notes', 'Running Balance']],
      body: rows,
      theme: 'grid',
      headStyles: { fillColor: COL_NEON, textColor: [0, 0, 0], fontSize: 7, fontStyle: 'bold' },
      bodyStyles: { fillColor: COL_CARD, textColor: COL_WHITE, fontSize: 6, lineColor: COL_BORDER },
      alternateRowStyles: { fillColor: COL_BG },
      margin: { left: M, right: M },
      styles: { cellPadding: 2 },
      tableWidth: CW,
    })
  }

  const totalPages = doc.internal.getNumberOfPages()
  for (let i = 2; i <= totalPages; i++) {
    doc.setPage(i)
    addFooter(doc, i, totalPages)
  }
  const blob = doc.output('blob')
  const dataUri = doc.output('datauristring')
  return { blob, dataUri, doc, pageCount: totalPages }
}

export function generateMonthlyStatement(transactions, year, month) {
  const doc = new jsPDF('p', 'mm', 'a4')
  doc.setFont('helvetica')
  let pageNum = 1

  const monthName = new Date(year, month).toLocaleString('en-US', { month: 'long' })
  const periodLabel = `${monthName} ${year}`

  doc.setFillColor(...COL_CARD)
  doc.rect(0, 0, PW, PH, 'F')
  doc.setFillColor(...COL_BG)
  doc.rect(M, M, CW, PH - 2 * M, 'F')
  const cx = PW / 2
  doc.setFontSize(30)
  doc.setTextColor(...COL_NEON)
  doc.text('ShyBlack', cx, 80, { align: 'center' })
  doc.setFontSize(14)
  doc.setTextColor(100, 255, 180)
  doc.text('FINANCE', cx, 96, { align: 'center' })
  doc.setDrawColor(...COL_NEON)
  doc.setLineWidth(0.5)
  doc.line(cx - 15, 104, cx + 15, 104)
  doc.setFontSize(18)
  doc.setTextColor(...COL_WHITE)
  doc.text('Monthly Finance Statement', cx, 126, { align: 'center' })
  doc.setFontSize(11)
  doc.setTextColor(...COL_MUTED)
  doc.text(periodLabel, cx, 144, { align: 'center' })
  doc.text(`Generated: ${new Date().toLocaleDateString()}`, cx, 162, { align: 'center' })
  doc.setFontSize(8)
  doc.setTextColor(...COL_MUTED)
  doc.text('ShyBlack Finance \u2022 Confidential', cx, 250, { align: 'center' })

  pageNum++
  addNewPage(doc, pageNum, 0)

  const monthStart = `${year}-${String(month + 1).padStart(2, '0')}-01`
  const lastDay = new Date(year, month + 1, 0).getDate()
  const monthEnd = `${year}-${String(month + 1).padStart(2, '0')}-${String(lastDay).padStart(2, '0')}`
  const filtered = transactions.filter((t) => t.date >= monthStart && t.date <= monthEnd)
  const totalIncome = filtered.filter((t) => t.type === 'income').reduce((s, t) => s + t.amount, 0)
  const totalExpense = filtered.filter((t) => t.type === 'expense').reduce((s, t) => s + t.amount, 0)
  const savings = totalIncome - totalExpense
  const savingsRate = totalIncome > 0 ? (savings / totalIncome) * 100 : 0

  let y = 25
  y = drawSectionHeader(doc, 'Monthly Summary', y)
  const cardW = (CW - 6) / 2
  const cardH = 28
  const sm = [
    { label: 'Total Income', value: fmt(totalIncome), color: COL_INCOME },
    { label: 'Total Expenses', value: fmt(totalExpense), color: COL_EXPENSE },
    { label: 'Savings', value: fmt(savings), color: savings >= 0 ? COL_INCOME : COL_EXPENSE },
    { label: 'Savings Rate', value: `${savingsRate.toFixed(1)}%`, color: COL_NEON },
  ]
  sm.forEach((card, i) => {
    const col = i % 2
    const row = Math.floor(i / 2)
    const cx2 = M + col * (cardW + 6)
    const cy = y + row * (cardH + 6)
    drawSummaryCard(doc, card.label, card.value, card.color, cx2, cy, cardW, cardH)
  })
  y = y + 2 * (cardH + 6) + 8

  if (y > PH - 50) {
    pageNum++
    addNewPage(doc, pageNum, pageNum)
    y = 25
  }

  const expByCat = {}
  filtered.filter((t) => t.type === 'expense').forEach((t) => {
    expByCat[t.category] = (expByCat[t.category] || 0) + t.amount
  })
  const catEntries = Object.entries(expByCat).sort((a, b) => b[1] - a[1])

  y = drawSectionHeader(doc, 'Expense by Category', y)
  if (catEntries.length === 0) {
    doc.setFontSize(9)
    doc.setTextColor(...COL_MUTED)
    doc.text('No expenses for this month.', M, y + 10)
    y += 16
  } else {
    const catRows = catEntries.map(([catId, amt]) => {
      const catDef = ALL_CATEGORIES.find((c) => c.id === catId)
      const pct = totalExpense > 0 ? (amt / totalExpense) * 100 : 0
      return [(catDef && catDef.label) || catId, fmt(amt), `${pct.toFixed(1)}%`]
    })
    doc.autoTable({
      startY: y + 4,
      head: [['Category', 'Amount', '%']],
      body: catRows,
      theme: 'grid',
      headStyles: { fillColor: COL_NEON, textColor: [0, 0, 0], fontSize: 7, fontStyle: 'bold' },
      bodyStyles: { fillColor: COL_CARD, textColor: COL_WHITE, fontSize: 6, lineColor: COL_BORDER },
      alternateRowStyles: { fillColor: COL_BG },
      margin: { left: M, right: M },
      styles: { cellPadding: 2 },
      tableWidth: CW,
    })
    y = doc.lastAutoTable.finalY + 10
  }

  if (y > PH - 50) {
    pageNum++
    addNewPage(doc, pageNum, pageNum)
    y = 25
  }

  y = drawSectionHeader(doc, 'Transaction List', y)
  const sortedTxns = [...filtered].sort((a, b) => b.date.localeCompare(a.date))
  if (sortedTxns.length === 0) {
    doc.setFontSize(9)
    doc.setTextColor(...COL_MUTED)
    doc.text('No transactions this month.', M, y + 10)
  } else {
    const txnRows = sortedTxns.map((t) => {
      const catDef = ALL_CATEGORIES.find((c) => c.id === t.category)
      return [
        t.date || '-',
        (catDef && catDef.label) || t.category || '-',
        t.type === 'income' ? fmt(t.amount) : '',
        t.type === 'expense' ? fmt(t.amount) : '',
        t.note || '',
      ]
    })
    doc.autoTable({
      startY: y + 4,
      head: [['Date', 'Category', 'Income', 'Expense', 'Note']],
      body: txnRows,
      theme: 'grid',
      headStyles: { fillColor: COL_NEON, textColor: [0, 0, 0], fontSize: 7, fontStyle: 'bold' },
      bodyStyles: { fillColor: COL_CARD, textColor: COL_WHITE, fontSize: 6, lineColor: COL_BORDER },
      alternateRowStyles: { fillColor: COL_BG },
      margin: { left: M, right: M },
      styles: { cellPadding: 2 },
      tableWidth: CW,
    })
  }

  const totalPages = doc.internal.getNumberOfPages()
  for (let i = 2; i <= totalPages; i++) {
    doc.setPage(i)
    addFooter(doc, i, totalPages)
  }
  const blob = doc.output('blob')
  const dataUri = doc.output('datauristring')
  return { blob, dataUri, doc, pageCount: totalPages }
}

export function generateNetWorthStatement(accounts, debts, transactions) {
  const doc = new jsPDF('p', 'mm', 'a4')
  doc.setFont('helvetica')
  let pageNum = 1

  doc.setFillColor(...COL_CARD)
  doc.rect(0, 0, PW, PH, 'F')
  doc.setFillColor(...COL_BG)
  doc.rect(M, M, CW, PH - 2 * M, 'F')
  const cx = PW / 2
  doc.setFontSize(30)
  doc.setTextColor(...COL_NEON)
  doc.text('ShyBlack', cx, 80, { align: 'center' })
  doc.setFontSize(14)
  doc.setTextColor(100, 255, 180)
  doc.text('FINANCE', cx, 96, { align: 'center' })
  doc.setDrawColor(...COL_NEON)
  doc.setLineWidth(0.5)
  doc.line(cx - 15, 104, cx + 15, 104)
  doc.setFontSize(18)
  doc.setTextColor(...COL_WHITE)
  doc.text('Net Worth Statement', cx, 126, { align: 'center' })
  doc.setFontSize(11)
  doc.setTextColor(...COL_MUTED)
  doc.text(`As of ${new Date().toLocaleDateString()}`, cx, 144, { align: 'center' })
  doc.setFontSize(8)
  doc.setTextColor(...COL_MUTED)
  doc.text('ShyBlack Finance \u2022 Confidential', cx, 250, { align: 'center' })

  pageNum++
  addNewPage(doc, pageNum, 0)

  const totalCash = transactions.reduce((s, t) => s + (t.type === 'income' ? t.amount : -t.amount), 0)
  const totalAccountBal = (accounts || []).reduce((s, a) => s + (a.balance || 0), 0)
  const totalAssets = totalCash + totalAccountBal
  const totalDebtBal = (debts || []).filter((d) => d.status !== 'settled').reduce((s, d) => s + (d.currentBalance ?? d.remainingAmount ?? 0), 0)
  const netWorth = totalAssets - totalDebtBal

  let y = 25
  y = drawSectionHeader(doc, 'Net Worth Overview', y)
  const cardW = (CW - 6) / 2
  const cardH = 28
  const nw = [
    { label: 'Total Assets', value: fmt(totalAssets), color: COL_INCOME },
    { label: 'Total Debts', value: fmt(totalDebtBal), color: COL_EXPENSE },
    { label: 'Net Worth', value: fmt(netWorth), color: netWorth >= 0 ? COL_NEON : COL_EXPENSE },
    { label: 'Accounts', value: String(accounts.length), color: COL_HEADING },
  ]
  nw.forEach((card, i) => {
    const col = i % 2
    const row = Math.floor(i / 2)
    const cx2 = M + col * (cardW + 6)
    const cy = y + row * (cardH + 6)
    drawSummaryCard(doc, card.label, card.value, card.color, cx2, cy, cardW, cardH)
  })
  y = y + 2 * (cardH + 6) + 8

  if (y > PH - 50) {
    pageNum++
    addNewPage(doc, pageNum, pageNum)
    y = 25
  }

  y = drawSectionHeader(doc, 'Accounts', y)
  if (accounts.length === 0) {
    doc.setFontSize(9)
    doc.setTextColor(...COL_MUTED)
    doc.text('No accounts configured.', M, y + 10)
    y += 16
  } else {
    const acctRows = accounts.map((a) => [a.name || '-', a.type || '-', fmt(a.balance || 0)])
    doc.autoTable({
      startY: y + 4,
      head: [['Name', 'Type', 'Balance']],
      body: acctRows,
      theme: 'grid',
      headStyles: { fillColor: COL_NEON, textColor: [0, 0, 0], fontSize: 7, fontStyle: 'bold' },
      bodyStyles: { fillColor: COL_CARD, textColor: COL_WHITE, fontSize: 6, lineColor: COL_BORDER },
      alternateRowStyles: { fillColor: COL_BG },
      margin: { left: M, right: M },
      styles: { cellPadding: 2 },
      tableWidth: CW,
    })
    y = doc.lastAutoTable.finalY + 12
  }

  if (y > PH - 50) {
    pageNum++
    addNewPage(doc, pageNum, pageNum)
    y = 25
  }

  y = drawSectionHeader(doc, 'Debts & Liabilities', y)
  const activeDebts = (debts || []).filter((d) => d.status !== 'settled')
  if (activeDebts.length === 0) {
    doc.setFontSize(9)
    doc.setTextColor(...COL_MUTED)
    doc.text('No active debts.', M, y + 10)
  } else {
    const debtRows = activeDebts.map((d) => [
      d.personName || '-',
      d.type === 'lent' ? 'Receivable' : 'Payable',
      fmt(d.originalAmount || 0),
      fmt(d.currentBalance ?? d.remainingAmount ?? 0),
    ])
    doc.autoTable({
      startY: y + 4,
      head: [['Person', 'Type', 'Original', 'Balance']],
      body: debtRows,
      theme: 'grid',
      headStyles: { fillColor: COL_NEON, textColor: [0, 0, 0], fontSize: 7, fontStyle: 'bold' },
      bodyStyles: { fillColor: COL_CARD, textColor: COL_WHITE, fontSize: 6, lineColor: COL_BORDER },
      alternateRowStyles: { fillColor: COL_BG },
      margin: { left: M, right: M },
      styles: { cellPadding: 2 },
      tableWidth: CW,
    })
  }

  const totalPages = doc.internal.getNumberOfPages()
  for (let i = 2; i <= totalPages; i++) {
    doc.setPage(i)
    addFooter(doc, i, totalPages)
  }
  const blob = doc.output('blob')
  const dataUri = doc.output('datauristring')
  return { blob, dataUri, doc, pageCount: totalPages }
}
